"""Render the static storefront from one set of package definitions. No dependencies."""
import html
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]


def money(cents):
    whole = f'{cents // 100:,}'.replace(',', '.')
    return f'R$ {whole},{cents % 100:02d}'


def render():
    data = json.loads((ROOT / 'packages.json').read_text(encoding='utf-8'))
    catalog = (ROOT / 'dist/catalog.js').read_text(encoding='utf-8')
    records = re.findall(r"^\s*\['([^']+)','([^']+)','([^']+)'", catalog, re.M)
    known = {row[0]: row[2] for row in records}
    assert len(known) == len(records), 'Duplicate catalog IDs'
    packs = data['packages']
    assert len({p['id'] for p in packs}) == len(packs), 'Duplicate package IDs'
    by_id = {p['id']: p for p in packs}
    for pack in packs:
        assert isinstance(pack['priceCents'], int) and pack['priceCents'] > 0
        assert all(s in known for s in pack.get('skillIds', [])), pack['id']
        selected = set(pack.get('skillIds', []))
        selected.update(s for s, cat in known.items() if cat in pack.get('skillCategories', []))
        for child in pack.get('includes', []):
            assert child in by_id and 'resolvedSkillIds' in by_id[child], 'Child packages must come first'
            selected.update(by_id[child]['resolvedSkillIds'])
        assert selected, f"Empty package: {pack['id']}"
        pack['resolvedSkillIds'] = [s for s in known if s in selected]
        pack['skillCount'] = len(selected)
    combo = by_id['completo']
    public_ids = combo['resolvedSkillIds']
    assert all(set(p['resolvedSkillIds']).issubset(public_ids) for p in packs)
    singles = [p for p in packs if not p.get('includes')]
    individual_total = sum(by_id[child]['priceCents'] for child in combo['includes'])
    assert individual_total > combo['priceCents']
    data['publicSkillIds'] = public_ids
    data['individualTotalCents'] = individual_total
    data['savingsCents'] = individual_total - combo['priceCents']
    js = '/* Generated by scripts/build_site.py from packages.json. */\nwindow.FRAMEBUILDS_STORE = ' + json.dumps(data, ensure_ascii=False, indent=2) + ';\n'
    (ROOT / 'dist/packages.js').write_text(js, encoding='utf-8')
    esc = html.escape
    cards = []
    for p in singles:
        outcomes = ''.join(f'<li>{esc(x)}</li>' for x in p['outcomes'])
        cards.append(f'''<article class="pack-card accent-{p['accent']}" id="pacote-{p['id']}">
          <div class="pack-card-head"><span class="pack-icon" aria-hidden="true">{p['symbol']}</span><span class="pack-count">{p['skillCount']} skills</span></div>
          <span class="eyebrow">{esc(p['label'])}</span><h3>{esc(p['name'])}</h3><p class="pack-description">{esc(p['description'])}</p>
          <div class="pack-price">{money(p['priceCents'])}<span>pagamento único</span></div><ul class="offer-list">{outcomes}</ul>
          <div class="pack-actions"><button class="button" type="button" data-purchase="{p['id']}">Quero este pacote <span aria-hidden="true">↗</span></button><button class="pack-details" type="button" data-package-details="{p['id']}" aria-label="Ver detalhes de {esc(p['name'])}">Ver skills e requisitos <span aria-hidden="true">+</span></button></div>
        </article>''')
    bundle_items = ''.join(f'<li><span>{esc(by_id[child]["name"])}</span><span>{money(by_id[child]["priceCents"])}</span></li>' for child in combo['includes'])
    launch_label = 'Pagamento seguro com Mercado Pago' if data.get('salesOpen') else 'Vendas em breve'
    section = f'''<section class="packages-section container section-space" id="pacote" aria-labelledby="packages-title">
      <div class="library-heading"><div><span class="eyebrow">ESCOLHA SEU PRÓXIMO PROJETO</span><h2 id="packages-title">Uma trilha para começar.<br><span class="muted-heading">Um pacote para cada objetivo.</span></h2></div><p>Compre a trilha que faz sentido para você.<br>Ou reúna todas no Framebuilds Completo.</p></div>
      <div class="purchase-terms"><span><i aria-hidden="true">✓</i> Pagamento único por pacote</span><span><i aria-hidden="true">✓</i> Sem mensalidade da biblioteca</span><span><i aria-hidden="true">✓</i> Veja as skills antes de escolher</span></div>
      <div class="packages-grid">{''.join(cards)}</div>
      <article class="bundle-card offer-card" id="pacote-completo"><div class="bundle-copy"><span class="eyebrow">{esc(combo['label'])}</span><h3>Um repertório completo.<br><span>Para a próxima ideia.<br>E para a que vier depois.</span></h3><p>{esc(combo['description'])}</p><div class="bundle-tags"><span>{len(singles)} pacotes</span><span>{combo['skillCount']} skills e rotinas</span><span>Pagamento único</span></div><button class="pack-details" type="button" data-package-details="completo">Ver tudo que está incluído <span aria-hidden="true">↗</span></button></div>
      <div class="bundle-offer"><span class="bundle-name">FRAMEBUILDS COMPLETO</span><ul class="bundle-breakdown">{bundle_items}</ul><div class="bundle-total"><span>Separadamente</span><span>{money(individual_total)}</span></div><div class="bundle-price">{money(combo['priceCents'])}<span>pagamento único</span></div><p class="bundle-saving">Economize {money(data['savingsCents'])} em relação aos quatro pacotes avulsos.</p><button class="button offer-button" type="button" data-purchase="completo">Quero todas as trilhas <span aria-hidden="true">↗</span></button><div class="offer-fine"><span class="status-dot"></span> {launch_label}</div></div></article>
      <p class="packages-footnote">Os pacotes reúnem instruções e fluxos de trabalho. Algumas skills fazem parte de um mesmo processo. Assinaturas de IA, contas, créditos e ferramentas externas não estão incluídos. Consulte os requisitos de cada pacote.</p>
    </section>'''
    options = ''.join(f'<option value="{p["id"]}">{esc(p["name"])}</option>' for p in packs)
    replacements = {
        'PACKAGES_SECTION': section,
        'PACKAGE_OPTIONS': options,
        'ENTRY_PRICE': money(min(p['priceCents'] for p in singles)),
        'COMBO_PRICE': money(combo['priceCents']),
        'PUBLIC_COUNT': str(len(public_ids)),
        'SALES_STATUS': 'Pagamento único. Acesso ao arquivo após confirmação.' if data.get('salesOpen') else 'A loja está em pré-lançamento.',
        'SALES_FAQ': esc(f"Escolha um pacote e conclua o pagamento no Mercado Pago. Após a confirmação, o arquivo fica disponível na página do seu pedido. Os pacotes têm pagamento único, a partir de {money(min(p['priceCents'] for p in singles))}, e o Framebuilds Completo custa {money(combo['priceCents'])}. Guarde seu link privado para voltar ao download por 30 dias após iniciar a compra. Não há envio automático por e-mail." if data.get('salesOpen') else f"As vendas ainda não estão abertas. Os pacotes têm pagamento único, a partir de {money(min(p['priceCents'] for p in singles))}, e o Framebuilds Completo custa {money(combo['priceCents'])}. Quando a compra estiver disponível, as condições de entrega e suporte serão apresentadas antes do pagamento."),
    }
    template = (ROOT / 'src/index.template.html').read_text(encoding='utf-8')
    for key, value in replacements.items():
        template = template.replace('{{' + key + '}}', value)
    assert not re.search(r'\{\{[A-Z_]+\}\}', template), 'Unresolved template variable'
    (ROOT / 'dist/index.html').write_text(template, encoding='utf-8')
    print(json.dumps({'packages': [{'id': p['id'], 'price': money(p['priceCents']), 'skills': p['skillCount']} for p in packs], 'public_skills': len(public_ids), 'savings': money(data['savingsCents'])}, ensure_ascii=False))


if __name__ == '__main__':
    render()
